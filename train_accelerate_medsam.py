# =============================================================================
# Conditioning context plumbing
# =============================================================================
# Per-batch foundation features. The training/validation loops set these via
# `cond_context()` around every forward call; the `_model_cond_pre_hook`
# attached to SwinFIRUNet reads them and injects as kwargs. This lets us reuse
# `edm_precond` / `edm_loss` / `edm_sample` from train_accelerate.py without
# changing their signatures.

_cond_tokens_ctx: contextvars.ContextVar[Optional[torch.Tensor]] = contextvars.ContextVar(
    "cond_tokens", default=None
)
_cond_global_ctx: contextvars.ContextVar[Optional[torch.Tensor]] = contextvars.ContextVar(
    "cond_global", default=None
)


@contextlib.contextmanager
def cond_context(tokens: Optional[torch.Tensor], global_: Optional[torch.Tensor]):
    """Set the cond contextvars for the duration of the block, then restore."""
    tt = _cond_tokens_ctx.set(tokens)
    tg = _cond_global_ctx.set(global_)
    try:
        yield
    finally:
        _cond_tokens_ctx.reset(tt)
        _cond_global_ctx.reset(tg)


def _model_cond_pre_hook(module, args, kwargs):
    """Forward-pre-hook that injects cond_* from contextvars.

    Only sets a kwarg when the caller hasn't already supplied it AND the
    contextvar holds a tensor.
    """
    t = _cond_tokens_ctx.get()
    g = _cond_global_ctx.get()
    if t is not None and "cond_tokens" not in kwargs:
        kwargs["cond_tokens"] = t
    if g is not None and "cond_global" not in kwargs:
        kwargs["cond_global"] = g
    return args, kwargs


def attach_cond_hook(model: nn.Module):
    """Register the cond-injection hook on `model`. Idempotent per-model."""
    if getattr(model, "_medsam_cond_hook_attached", False):
        return None
    handle = model.register_forward_pre_hook(_model_cond_pre_hook, with_kwargs=True)
    model._medsam_cond_hook_attached = True
    return handle


def pop_cond(batch: Dict, send_tokens: bool, send_global: bool):
    """Pop cond_tokens/cond_global from a batch dict, respecting cond_path.

    Always removes both keys if present (avoids dangling tensors in the batch).
    Returns (tokens, global_) where each is None if not requested.
    """
    t = batch.pop("cond_tokens", None) if isinstance(batch, dict) else None
    g = batch.pop("cond_global", None) if isinstance(batch, dict) else None
    if not send_tokens:
        t = None
    if not send_global:
        g = None
    return t, g


def to_device(x: Optional[torch.Tensor], device: torch.device):
    if x is None:
        return None
    return x.to(device, non_blocking=True)


