def parse_args():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cond_path", choices=["none", "global", "spatial", "both"],
                        default="both",
                        help="Which foundation-conditioning paths to enable.")
    parser.add_argument("--resume", type=str, default=None,
                        help="Path to a pre-MedSAM checkpoint (model weights "
                             "only, loaded with strict=False).")
    parser.add_argument("--data_dir", type=str, default=None)
    parser.add_argument("--output_dir", type=str, default=None)
    parser.add_argument("--num_epochs", type=int, default=None)
    parser.add_argument("--batch_size", type=int, default=None)
    parser.add_argument("--lr", type=float, default=None)
    parser.add_argument("--require_cache", action="store_true", default=True)
    parser.add_argument("--no_require_cache", dest="require_cache",
                        action="store_false")
    return parser.parse_args()


def main():
    args = parse_args()

    # Priority (lowest → highest): base_config → medsam_config → CLI args.
    cfg = dict(base_config)       # 1. all defaults from train_accelerate.py
    cfg.update(medsam_config)     # 2. MedSAM-specific overrides (edit at top of this file)

    # 3. CLI overrides
    if args.data_dir is not None:
        cfg["data_dir"] = args.data_dir
    if args.output_dir is not None:
        cfg["output_dir"] = args.output_dir
    if args.num_epochs is not None:
        cfg["num_epochs"] = args.num_epochs
    if args.batch_size is not None:
        cfg["batch_size"] = args.batch_size
    if args.lr is not None:
        cfg["lr"] = args.lr

    # MedSAM-specific cfg
    cfg["cond_path"] = args.cond_path
    cfg["pretrained_ckpt"] = args.resume
    cfg["require_cache"] = args.require_cache

    train(cfg)


if __name__ == "__main__":
    main()
