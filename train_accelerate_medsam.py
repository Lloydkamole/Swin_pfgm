"""
PFGM-FIR fine-tuning with MedSAM foundation conditioning.

This trainer mirrors `train_accelerate.py` 1:1 for every training feature
(EMA, CFG/CFG++/dynamic CFG, body-mask training, masked metrics, FSDP,
mixed precision, gradient checkpointing, gradient logging, ODE-trajectory
logging, train+val sample generation to TensorBoard, TTA validation,
warmup+cosine LR schedule, etc.). The only differences are MedSAM-specific:

  1. Model is built with `use_foundation_cond=True` (extra cross-attn +
     global-vector projection that consume MedSAM features).
  2. Optional `--resume` loads a pre-MedSAM checkpoint with strict=False so
     the new (zero-init) cond weights stay at their identity-equivalent
     defaults.
  3. Data pipeline uses `MedSAMSliceDataset`, which adds `cond_tokens` /
     `cond_global` to every batch from a pre-cached MedSAM feature file.
  4. Cond features are threaded into the model via a forward-pre-hook
     backed by `contextvars.ContextVar`s. The training/validation/sampling
     loops pop cond out of each batch and set the contextvars via the
     `cond_context` manager around every forward call. The hook then
     auto-injects them as kwargs to `SwinFIRUNet.forward`, so the existing
     `edm_precond` / `edm_loss` / `edm_sample` helpers (which know nothing
     about MedSAM) work unchanged.

`train_accelerate.py` is NOT modified; helpers are re-imported from it.

Usage
-----
    # Single GPU:
    python train_accelerate_medsam.py \
        --cond_path both \
        --resume outputs_accelerate/<run>/checkpoints/best/model.safetensors

    # Multi-GPU:
    accelerate launch train_accelerate_medsam.py --cond_path both --resume <ckpt>

    # The data dir must contain pre-cached MedSAM features:
    #   <data_dir>/<patient>/medsam_features.pt
    # Generated by:
    #   python -m Swin_pfgm.tools.precompute_medsam_features --data_dir ...

CLI flags override base_config values from `train_accelerate.config`.
"""

