def build_model(cfg: Dict) -> SwinFIRUNet:
    """Build SwinFIRUNet with `use_foundation_cond=True`.

    Mirrors the kwargs used by `create_swin_fir_unet(config='custom', ...)` in
    `train_accelerate.train()` so a checkpoint trained without MedSAM loads
    cleanly here with `strict=False`.
    """
    in_channels = 2
    return SwinFIRUNet(
        in_channels=in_channels,
        out_channels=1,
        base_channels=cfg["base_channels"],
        channel_mults=tuple(cfg["channel_mults"]),
        num_res_blocks=cfg["num_res_blocks"],
        radius_emb_dim=cfg["radius_emb_dim"],
        attention_resolutions=tuple(cfg["attention_resolutions"]),
        num_heads=cfg["num_heads"],
        window_size=cfg["window_size"],
        mlp_ratio=cfg["mlp_ratio"],
        num_swin_blocks=cfg["num_swin_blocks"],
        num_sfb_blocks=cfg["num_sfb_blocks"],
        num_bottleneck_blocks=cfg["num_bottleneck_blocks"],
        use_sfb=cfg["use_sfb"],
        dropout=cfg["dropout"],
        drop_path_rate=cfg["drop_path"],
        gradient_checkpoint=cfg["gradient_checkpoint"],
        attention_type=cfg["attention_type"],
        deformable_kwargs=cfg.get("deformable_kwargs", None),
        use_foundation_cond=True,
    )


def load_pretrained(model: nn.Module, ckpt_path: str, accelerator: Accelerator) -> None:
    """Load a pre-MedSAM checkpoint into the model with strict=False."""
    p = Path(ckpt_path)
    if not p.exists():
        raise FileNotFoundError(f"Checkpoint not found: {ckpt_path}")
    if p.suffix == ".safetensors":
        from safetensors.torch import load_file
        state = load_file(str(p))
    else:
        state = torch.load(str(p), map_location="cpu", weights_only=False)
        if isinstance(state, dict) and "state_dict" in state:
            state = state["state_dict"]
    state = {k.replace("module.", "", 1) if k.startswith("module.") else k: v
             for k, v in state.items()}
    missing, unexpected = model.load_state_dict(state, strict=False)
    if accelerator.is_main_process:
        non_cond_missing = [
            k for k in missing
            if not k.startswith(("cond_global_proj", "bottleneck_xattn", "context_proj"))
            and k != "bottleneck_xattn_gate"
        ]
        print(f"[ckpt] loaded {ckpt_path}")
        print(f"[ckpt] missing total={len(missing)}  non-cond missing={len(non_cond_missing)}")
        if non_cond_missing:
            print(f"[ckpt] WARNING non-cond missing keys: {non_cond_missing[:8]}")
        if unexpected:
            print(f"[ckpt] WARNING unexpected keys: {unexpected[:8]}")


